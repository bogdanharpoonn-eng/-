  var currentLang = localStorage.getItem("lang") === "en" ? "en" : "uk";

  function applyLang(lang) {
    currentLang = lang === "en" ? "en" : "uk";
    localStorage.setItem("lang", currentLang);
    document.documentElement.lang = currentLang;
    var dict = I18N[currentLang];
    [].slice.call(document.querySelectorAll("[data-i18n]")).forEach(function (el) {
      var k = el.getAttribute("data-i18n");
      if (dict[k] != null) el.textContent = dict[k];
    });
    [].slice.call(document.querySelectorAll("[data-i18n-aria]")).forEach(function (el) {
      var k = el.getAttribute("data-i18n-aria");
      if (dict[k] != null) el.setAttribute("aria-label", dict[k]);
    });
    [].slice.call(document.querySelectorAll(".lang-switch button")).forEach(function (b) {
      b.classList.toggle("is-on", b.getAttribute("data-lang") === currentLang);
    });
  }

  applyLang(currentLang);
  document.addEventListener("click", function (e) {
    var btn = e.target.closest(".lang-switch button");
    if (!btn) return;
    applyLang(btn.getAttribute("data-lang"));
  });

  var root = document.getElementById("heroSlider");
  if (root) {
    var slides = [].slice.call(root.querySelectorAll(".slide"));
    var dotsWrap = document.getElementById("dots");
    var i = 0;
    var timer;

    slides.forEach(function (_, n) {
      var b = document.createElement("button");
      b.type = "button";
      b.setAttribute("aria-label", "Slide " + (n + 1));
      if (n === 0) b.className = "is-on";
      b.addEventListener("click", function (e) {
        e.preventDefault();
        e.stopPropagation();
        go(n);
      });
      dotsWrap.appendChild(b);
    });
    var dots = [].slice.call(dotsWrap.querySelectorAll("button"));

    function go(n) {
      slides[i].classList.remove("is-on");
      dots[i].classList.remove("is-on");
      i = (n + slides.length) % slides.length;
      slides[i].classList.add("is-on");
      dots[i].classList.add("is-on");
      restart();
    }
    function restart() {
      clearInterval(timer);
      timer = setInterval(function () { go(i + 1); }, 5000);
    }
    root.querySelector(".arr.prev").addEventListener("click", function (e) {
      e.preventDefault();
      e.stopPropagation();
      go(i - 1);
    });
    root.querySelector(".arr.next").addEventListener("click", function (e) {
      e.preventDefault();
      e.stopPropagation();
      go(i + 1);
    });
    restart();
  }

